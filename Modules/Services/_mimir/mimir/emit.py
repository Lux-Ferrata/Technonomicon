"""Write the generated courseInstances/: the Practice instance and one Homework assessment per plan.

The Tn-mimir module mounts this directory read-only over the course repo's
empty courseInstances/, so nothing generated reaches git or Syncthing.
Everything is validated against PL's own JSON schemas (vendored from the
pinned image) before it is written, and written atomically.
"""

import json
import shutil
import uuid
from datetime import date, timedelta
from importlib import resources
from pathlib import Path

import jsonschema

from .catalog import Catalog
from .config import Study, local_stamp
from .planner import Plan

NS = uuid.UUID("6f1d8a52-3c4b-4e1f-9a7d-0b2c5e8f4a61")  # Mimir's namespace for generated uuids
INSTANCE = "Practice"
SET = "Practice"
KEEP_DAYS = 14
MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")
WEEKDAY = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")


def schema(name: str) -> dict:
    return json.loads(resources.files("mimir").joinpath(f"schemas/{name}.json").read_text())


def _write_json(path: Path, obj: dict, schema_name: str) -> None:
    jsonschema.validate(obj, schema(schema_name))
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(obj, indent=2) + "\n")
    tmp.replace(path)


def course_instance(tz_name: str) -> dict:
    return {
        "uuid": str(uuid.uuid5(NS, f"course-instance:{INSTANCE}")),
        "longName": INSTANCE,
        "timezone": tz_name,
        "comment": "Generated by mimir; do not edit.",
        "selfEnrollment": {"enabled": True, "restrictToInstitution": False, "useEnrollmentCode": False},
        "publishing": {"startDate": "2026-01-01T00:00:00", "endDate": "2099-12-31T23:59:59"},
    }


def ensure_course_instance(generated: Path, tz_name: str) -> None:
    _write_json(generated / INSTANCE / "infoCourseInstance.json", course_instance(tz_name), "infoCourseInstance")


def tid_for(day: date, mode: str, existing: set[str]) -> str:
    if mode == "daily":
        return day.isoformat()
    n = 1
    while f"{day.isoformat()}-{mode}{n}" in existing:
        n += 1
    return f"{day.isoformat()}-{mode}{n}"


def title(plan: Plan) -> str:
    d = plan.day
    head = f"{WEEKDAY[d.weekday()]} {d.day} {MONTHS[d.month - 1]}"
    parts = []
    if r := len(plan.zone("Review")):
        parts.append(f"{r} review{'s' if r != 1 else ''}")
    if n := len(plan.zone("New")):
        parts.append(f"{n} new")
    if lg := plan.zone("Long"):
        parts.append("long: " + ", ".join(i.skill.title for i in lg))
    kind = {"daily": "", "more": " · extra", "long": " · long"}[plan.mode]
    return f"{head}{kind} · {', '.join(parts)} · ~{round(plan.minutes)} min"


def _entry(cat: Catalog, item) -> dict:
    e = {"id": item.template.qid, "autoPoints": 1, "triesPerVariant": 2}
    if item.learning:
        e["maxAutoPoints"] = item.skill.learn
        if item.template.declares_learn:
            e["preferences"] = {"learn": True}
    else:
        e["maxAutoPoints"] = 1
    return e


def assessment(cat: Catalog, plan: Plan, tid: str, study: Study) -> dict:
    zones = []
    for z, heading in (("Review", "Review"), ("New", "New"), ("Long", "Long")):
        items = plan.zone(z)
        if items:
            zones.append({"title": heading, "questions": [_entry(cat, i) for i in items]})
    nxt = plan.day + timedelta(days=1)
    suffix = tid[len(plan.day.isoformat()):].replace("-", "")
    return {
        "uuid": str(uuid.uuid5(NS, f"assessment:{tid}")),
        "type": "Homework",
        "title": title(plan),
        "set": SET,
        "number": plan.day.strftime("%Y%m%d") + suffix,
        "comment": "Generated by mimir; do not edit.",
        "constantQuestionValue": True,
        "shuffleQuestions": True,
        "text": ("<p>A wrong answer brings new numbers: keep going until each question is done. "
                 "New skills start with a worked example and need a few correct variants.</p>"),
        "accessControl": [{"dateControl": {
            "release": {"date": local_stamp(plan.day, study.day_start_hour)},
            "due": {"date": local_stamp(nxt, study.day_start_hour)},
        }}],
        "zones": zones,
    }


def write_assessment(generated: Path, cat: Catalog, plan: Plan, tid: str, study: Study) -> Path:
    path = generated / INSTANCE / "assessments" / tid / "infoAssessment.json"
    _write_json(path, assessment(cat, plan, tid, study), "infoAssessment")
    return path


def prune(generated: Path, today: date, final_tids: set[str]) -> list[str]:
    """Remove assessments older than KEEP_DAYS whose reviews are final in the log."""
    from .ingest import tid_day

    root = generated / INSTANCE / "assessments"
    removed = []
    if not root.is_dir():
        return removed
    for d in sorted(root.iterdir()):
        day = tid_day(d.name)
        if day is not None and day < today - timedelta(days=KEEP_DAYS) and d.name in final_tids:
            shutil.rmtree(d)
            removed.append(d.name)
    return removed
